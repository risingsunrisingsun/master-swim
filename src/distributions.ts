/**
 * 국내 마스터즈 기록 분포.
 *
 * 마이랭킹의 "기록 분포" 화면 캡처에서 옮긴 히스토그램이다. 백분위 표를 직접 받은
 * 것이 아니므로 다음 한계를 안고 있다.
 *
 * - `total` 은 화면에 표시된 값이라 정확하다. 백분위는 비율만 쓰므로
 *   `counts` 의 절대 크기가 아니라 **모양**이 결과를 정한다.
 * - 원본은 **연대**(20대·30대…)로 묶여 있다. 이 앱의 5세 연령부는 연대로 접어서 쓴다.
 *
 * 값이 틀렸다고 판단되면 이 파일의 배열만 고치면 된다 — 계산·화면·테스트는
 * 손대지 않는다.
 *
 * ## `counts` 를 어떻게 얻었나 — 종목에 따라 다르다
 *
 * **자유형·배영은 눈으로 읽은 추정치다.** 340건과 370건을 구분할 수 없다. 백분위는
 * 누적합으로 계산되므로 개별 오차는 상당히 상쇄되지만, 중앙값 기준 ±0.5~1초, 꼬리는
 * 그보다 큰 오차를 가정해야 한다.
 *
 * **평영·접영은 캡처의 픽셀에서 뽑았다.** 그래프의 점 마커 중심을 찾아 0건 기준선
 * 대비 높이를 재고, 그 높이의 합이 화면에 표시된 표본 수가 되도록 스케일을 역산했다.
 * 눈으로 읽은 값은 표본 수와 첫 x축 라벨 두 개뿐이다.
 *
 * 이 방법이 정확하다는 근거가 있다. 표본이 적은 네 분포(300~409건)에서는 마커 높이가
 * 정수 배로 양자화되어 나오고, 거기서 역산한 건수의 합이 **표시된 표본 수와 정확히
 * 일치한다** — 300, 326, 384, 409 네 개 모두. 추정이 아니라 원본 그대로다.
 *
 * ## 60초 경계의 팬텀 구간
 *
 * `F/20/breast` 와 `F/40/breast` 는 60초 자리에 **값이 없는 구간 두 개**가 그려져
 * 있고 엉뚱한 라벨(`67초`)이 붙어 있다. 마이랭킹이 60초를 넘는 기록의 표기를
 * `m:ss` 로 바꾸면서 생긴 렌더링 부산물로 보인다.
 *
 * 그 둘을 빼면 첫 라벨부터 1초씩 연속이 되고 이후 라벨이 전부 맞아떨어진다 —
 * `F/20/breast` 는 33초 시작 · 45구간 · 마지막 `1:17` 로 닫힌다. 그래서 팬텀은
 * 빼고 넣었다.
 *
 * ## 아직 의심스러운 곳
 *
 * **50대 여덟 분포 전부**(네 영법 × 남녀)에서 **상위 5% 커트라인이 20~40대보다
 * 빠르게** 나온다. 평영·접영을 붙이면서 8/8 이 된 셈이고, 50대 부근 표시는 어느
 * 영법에서도 신뢰도가 낮다.
 *
 * `F/50/free` 는 여기서 한 발 더 나간다 — **중앙값까지** 40대보다 빠르다. 나머지
 * 일곱은 중앙값이 연대 순서를 지킨다. 테스트는 성립하는 범위만 고정한다
 * (`distributions.test.ts`).
 *
 * 원본 캡처와 한 칸씩 대조했다 — **읽기 오류가 아니다.** 23~28초의 넓은 평지는
 * 마이랭킹 그래프에 실제로 그려져 있고 여기 적힌 값은 그것을 정확히 옮긴 것이다.
 * 그래서 이 배열을 고쳐서 없앨 수 있는 문제가 아니다.
 *
 * 원본을 의심하는 근거 두 개:
 *
 * - **50대 그래프가 40대보다 왼쪽에서 시작한다** — 여덟 조합 모두. 자유형 남자는
 *   40대가 25초, 50대가 23초에서 시작한다. 접영 남자는 27초 대 24초, 평영 여자는
 *   35초 대 32초다. 50대에 더 빠른 사람이 있다는 뜻이 되어 연대 순서와 반대다.
 * - **40대에는 같은 평지가 없다.** "은퇴한 경영 선수가 50대에 섞였다"는 설명이라면
 *   40대에도 나타나야 한다. 50대에서만, 그리고 여덟 조합 전부에서 나타나는 것은
 *   원본의 집계 방식(릴레이 구간·특별부 포함 등)을 의심하게 만든다.
 *
 * **고치지 않고 이 값으로 간다**(ADR-0006). 50대 회원의 상위 % 는 실제보다 유리하게
 * 나올 수 있고, 화면이 표본 수와 오차 안내를 함께 띄우는 것으로 버틴다. 뒤집고 싶어지면
 * 마이랭킹의 "나의 순위 확인"(기록을 넣으면 순위를 돌려준다)에서 종목당 점 몇 개를
 * 찍는 것이 가장 싼 길이다.
 *
 * 25m·100m 과 개인혼영은 분포를 수집하지 않기로 했다. 그 종목은 `level-band` 로 남는다.
 *
 * 출처: 마이랭킹(myranking.co.kr) 기록 분포 화면. 자동 수집하지 않았다 —
 * `robots.txt` 가 검색엔진 넷 외 전체를 차단한다. 자유형·배영과 평영 8장은
 * 데스크톱, 나머지 평영·접영 12장은 휴대폰 화면 캡처다.
 */
